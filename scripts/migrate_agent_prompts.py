    # Write prompts to a JSON file
    data = {}
    for agent_id, info in AGENTS.items():
        data[agent_id] = info["prompt"]

    json_path = "/tmp/agent_prompts.json"
    with open(json_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False)

    print(f"Written {len(data)} agent prompts to {json_path}")
    print(f"Total characters: {sum(len(v) for v in data.values())}")

    # Generate SQL update statements
    sql_statements = []
    for agent_id, prompt in data.items():
        escaped = prompt.replace("\\", "\\\\").replace("'", "\\'")
        sql_statements.append(
            f"UPDATE agent_configs SET system_prompt = '{escaped}' WHERE id = '{agent_id}';"
        )

    sql_file = "/tmp/update_agent_prompts.sql"
    with open(sql_file, "w", encoding="utf-8") as f:
        f.write("\n".join(sql_statements))

    print(f"Generated SQL file: {sql_file}")
    print("Run on server:")
    print(f"  docker cp {sql_file} idea-arena-mysql-1:/tmp/update.sql")
